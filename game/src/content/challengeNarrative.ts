export function challengeNarrative(templateId: string, decision: string): ChallengeNarrative {
  const brief = invitations[templateId];
  if (!brief) throw new Error('长期委托缺少独立开场。');
  return {
    brief,
    hint: `这次要练的是：${decision}先看当前目标和已经收到的材料，再检查失败回执；旧委托的具体数值不能替本轮证据。`,
    rules: ['相同编号会带来相同现场；新编号可能改变材料、前置、权限和费用。', '只有实际取得的资料能供伙伴使用。法器、观察与复查按本轮显示的成本执行。', '旧经验可以帮你提出下一步，完成仍须满足这张契约的实际条件。'],
    recap: {
      story: '这张委托留下的是你本次实际做过的事。沿着回响看一遍：哪里改变了世界，哪里只改变了伙伴知道的东西？',
      system: `本轮练习：${decision}观察、请求、回执和验收各有时点。下方只列当时已经取得的证据，不能用后来知道的事替早先的决策。`,
      technical: '这一变体使用确定的教学模拟。种子决定场景，已经记录的动作重建执行结果；它不复现语言模型的内部计算，也不把换编号算作独立迁移。',
    },
  };
}
